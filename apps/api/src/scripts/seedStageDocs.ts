function doc(name: string): StageDoc {
  const kind = name.startsWith('Приказ') ? 'Приказ' : name.startsWith('Положение') ? 'Положение' : name.startsWith('СОП') ? 'СОП' : name.startsWith('Журнал') ? 'Журнал' : 'Документ';
  return {
    name,
    template: `${kind}\n\nОрганизация: {{org}}\nИНН: {{inn}}\nДата: {{date}}\nДокумент: ${name}\nОтветственный: {{responsible}}\n`,
  };
}


async function main() {
  const prisma = getPrismaClient();
  const store = new PrismaChannelStore(prisma);
  const current = await store.get<Stage[]>('platform', null, 'stage_docs', []);
  if (current.data.length) {
    console.log(`Канал 'stage_docs' уже содержит ${current.data.length} этапов — пропускаю (не перезаписываю правки методиста).`);
    await prisma.$disconnect();
    return;
  }
  const res = await store.set('platform', null, 'stage_docs', SEED, { expectedVersion: 0, updatedBy: null });
  if (!res.ok) throw new Error('Не удалось записать начальный каталог этапов — конфликт версий');
  console.log(`Записано ${SEED.length} этапов в канал 'stage_docs' (версия ${res.version}).`);
  await prisma.$disconnect();
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});

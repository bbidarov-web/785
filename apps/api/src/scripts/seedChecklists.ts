/**
 * Начальные данные миграции — каталог чек-листов методиста (SERVER.md §7:
 * "Эталонные справочники стоит перенести как начальные данные миграции").
 * Содержимое дословно перенесено из запасного каталога в
 * `reference/prototype/Обход - мобильный.dc.html` (константа `base`, строки
 * ~1072–1094) — это не демо-фикстура, а реальные типовые чек-листы 785н,
 * которые в проде публикует методист, здесь — стартовое наполнение канала.
 *
 * Запуск на сервере: docker compose exec api node dist/scripts/seedChecklists.js
 * Идемпотентен: пишет только если канал 'checklists' ещё пуст.
 */
import { getPrismaClient } from '../infra/prisma/client.js';
import { PrismaChannelStore } from '../infra/prisma/channelStore.js';
import type { ChecklistDef } from '../shared/channelShapes.js';

const SEED: ChecklistDef[] = [
  {
    name: 'Чек-лист аудита процедурного кабинета',
    items: [
      'Термолабильные препараты хранятся при +2…+8 °C, есть термометр и термокарта?',
      'Журнал термометрии холодильников заполняется 2 раза в сутки?',
      'Препараты ПКУ хранятся в сейфе, ведётся предметно-количественный учёт?',
      'Укладка при анафилаксии укомплектована, сроки годности в норме?',
      'На рабочем месте есть действующий СОП и инструкция по хранению ЛП?',
      'Препараты с истекшим сроком годности изолированы и промаркированы?',
    ],
  },
  {
    name: 'Чек-лист аудита стерилизационной',
    items: [
      'Режимы стерилизации соблюдаются, журнал контроля заполнен?',
      'Химические индикаторы вклеены в журнал за текущую неделю?',
      'Упаковка простерилизованных изделий не нарушена, срок годности читается?',
      'Разделение зон «грязная / чистая» соблюдается?',
    ],
  },
  {
    name: 'Чек-лист обращения с медицинскими отходами',
    items: [
      'Ёмкости класса Б промаркированы и заполнены не более чем на 3/4?',
      'Одноразовые пакеты соответствуют классу отходов по цвету?',
      'Журнал учёта вывоза отходов заполнен за текущий месяц?',
      'Персонал использует СИЗ при обращении с отходами?',
      'Место временного хранения закрыто и промаркировано?',
    ],
  },
];

async function main() {
  const prisma = getPrismaClient();
  const store = new PrismaChannelStore(prisma);
  const current = await store.get<ChecklistDef[]>('platform', null, 'checklists', []);
  if (current.data.length) {
    console.log(`Канал 'checklists' уже содержит ${current.data.length} записей — пропускаю (не перезаписываю правки методиста).`);
    await prisma.$disconnect();
    return;
  }
  const res = await store.set('platform', null, 'checklists', SEED, { expectedVersion: 0, updatedBy: null });
  if (!res.ok) throw new Error('Не удалось записать начальный каталог чек-листов — конфликт версий');
  console.log(`Записано ${SEED.length} эталонных чек-листов в канал 'checklists' (версия ${res.version}).`);
  await prisma.$disconnect();
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
